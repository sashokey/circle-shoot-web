import { readdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
if (!process.env.WASI_SDK_PATH) throw new Error('Set WASI_SDK_PATH to a WASI SDK 34 installation.');
const sdk = resolve(process.env.WASI_SDK_PATH);
const compiler = resolve(sdk, 'bin', process.platform === 'win32' ? 'clang++.exe' : 'clang++');
if (!existsSync(compiler)) throw new Error('Set WASI_SDK_PATH.');
const scan = path => readdirSync(path, {withFileTypes: true}).flatMap(item => item.isDirectory() ? scan(resolve(path, item.name)) : item.name.endsWith('.cpp') ? [resolve(path, item.name)] : []);
const sources = scan(resolve(root, 'src'));
const exports = ['malloc', 'free', 'web_resource', 'web_font', 'web_sound', 'web_register_file', 'web_prepare', 'web_init', 'web_start', 'web_resume', 'web_tick', 'web_draw', 'web_pointer', 'web_click', 'web_press', 'web_release', 'web_window', 'web_key', 'web_pause', 'web_continue', 'web_save', 'web_snapshot', 'web_balls', 'web_levels', 'web_qa'];
const args = ['--target=wasm32-wasip1', '--sysroot=' + resolve(sdk, 'share/wasi-sysroot'), '-std=c++17', '-O2', '-fwasm-exceptions', '-fno-rtti', '-DNDEBUG', '-I' + resolve(root, 'src/platform'), '-I' + resolve(root, 'src/game'), '-include', resolve(root, 'src/platform/WebFramework.h'), '-mexec-model=reactor', '-Wno-delete-incomplete', '-Wno-shift-op-parentheses', '-Wno-return-type', '-Wno-parentheses', ...sources, '-Wl,--export-memory', '-Wl,-z,stack-size=2097152', '-Wl,--initial-memory=16777216', '-Wl,--max-memory=268435456', ...exports.map(name => '-Wl,--export=' + name), '-lm', '-o', resolve(root, 'game.wasm')];
args.splice(2, 0, '-stdlib=libc++', '-isystem', resolve(sdk, 'share/wasi-sysroot/include/wasm32-wasip1/eh/c++/v1'), '-L' + resolve(sdk, 'share/wasi-sysroot/lib/wasm32-wasip1/eh'));
args[args.indexOf('-std=c++17')] = '-std=c++20';
args.push('-lunwind');
args.push('-mllvm', '-wasm-use-legacy-eh=false');
args.push('-DRELEASEFINAL');
const result = spawnSync(compiler, args, {cwd: root, encoding: 'utf8', windowsHide: true});
process.stdout.write(result.stdout || '');
process.stderr.write(result.stderr || '');
if (result.error) throw result.error;
process.exitCode = result.status || 0;
